/**
 * 테마 상세 블록의 세로 리듬.
 *
 * 예전에는 '한 화면에 블록 하나' 였다 — 블록마다 화면 높이(min-h)를 차지하고,
 * 스크롤이 경계에 붙고(ScreenSnap), 한 화면에 안 들어가면 transform 으로
 * 줄였다(ScreenFit). 2026-10-04 에 **전부 걷어냈다**: 내용이 적은 블록
 * ('추천', '진행 순서')이 데스크톱에서 절반 이상 비어 보였고, 그 빈 공간이
 * 고정 높이 탓이었다(UX 진단).
 *
 * 지금은 이렇게 나뉜다:
 *   인트로(테마 소개)  데스크톱에서만 한 화면 높이 — 아래 INTRO_SCREEN_SECTION
 *   그 외 모든 블록    높이는 내용에 맡기고 **여백만** (데스크톱 128px, 모바일 64px)
 *
 * 스크롤 스냅(경계에 달라붙기)은 **돌아오지 않았다.** 되돌린 건 높이뿐이다 —
 * 스냅은 내용이 화면보다 길면 중간을 아예 못 보게 만드는 알려진 문제가 있다.
 *
 * ⚠️ 홈(/)의 스크롤텔링은 이것과 무관하다. 전혀 다른 구조이고(ScrollStage)
 *    코드를 한 줄도 공유하지 않는다 — 여기를 고쳐도 홈은 바뀌지 않는다.
 * ⚠️ Tailwind 가 소스에서 클래스 이름을 찾으므로 문자열을 조립하지 말고 통째로 둔다.
 */

/*
  블록 **사이** 간격이 모바일 64px · 데스크톱 128px 이 되게 한다.

  ⚠️ 블록마다 위아래로 들어가므로 이웃한 두 블록의 여백이 더해진다. 그래서 목표
     간격의 **절반**을 적는다 — 처음에 96px(py-24)을 그대로 적었더니 블록 사이가
     192px 으로 벌어져 '추천' 과 '콘텐츠 구성' 사이가 한 화면 가까이 비었다.

  데스크톱을 96 → 128px 로 넓혔다(2026-10-07). 96px 일 때 "위아래로 답답하게
  이어진다" 는 의견이 있었고, 여백이 충분하면 본문 이해도가 올라간다는 근거도
  있다(Chaparro 외 — 읽는 사람의 80%가 여백 많은 쪽을 선호).
*/
export const SCREEN_SECTION = "py-8 md:py-16";

/**
 * 첫 화면(테마 소개) 전용.
 *
 * **데스크톱에서는 한 화면을 차지한다**(2026-10-07 복원). 2026-10-04 에 스냅 구조를
 * 걷어내면서 모든 블록의 고정 높이를 없앴는데, 그 뒤 데스크톱 첫 화면에 블록이
 * 세 개까지 들어와 "정보를 한번에 왕창 보여준다" 는 의견이 나왔다(1272px 높이 창
 * 실측: 소개 + 회차 선택 + 추천).
 *
 * ⚠️ **인트로에만** 준다. 걷어낸 이유였던 "내용이 적은 블록이 절반 넘게 비어
 *    보인다" 는 '추천' · '진행 순서' 쪽 이야기였고, 인트로는 포스터 · 스펙 · 장르 ·
 *    시놉시스로 차 있어 해당하지 않는다. 다른 블록에 이 값을 쓰지 말 것.
 * ⚠️ 높이는 var(--header-height) 를 빼서 헤더를 따라간다(Header.tsx 가 실측해 넣는다).
 *    svh 를 쓰는 건 모바일 주소창이 접힐 때 화면이 튀지 않게 하기 위함이다.
 *
 * ⚠️ **세로 가운데 정렬을 쓰지 않는다.** 가운데에 두면 남는 공간이 위아래로 반씩
 *    갈리는데, 1272px 높이 창에서 위 여백만 295px 이 됐다("살짝 과하다",
 *    2026-10-07). 남는 공간은 신청하기 버튼 **아래**로 보낸다.
 *
 * ⚠️ 위 여백은 한때 화면 높이에 비례했다(clamp(2rem,12svh,11rem) — 800px 노트북에서
 *    96px). 모드 선택 창이 들어오면서 소개 내용이 늘어 **그 여백만큼 섹션이 한
 *    화면을 넘겼고**, 하한이던 2rem 으로 고정했다(2026-10-09). 여백을 다시 키우려면
 *    안쪽 내용부터 줄일 것 — 안 그러면 첫 화면에 안 들어간다.
 */
export const INTRO_SCREEN_SECTION =
  "pt-6 pb-7 md:pb-8 md:flex md:flex-col md:min-h-[calc(100svh-var(--header-height,72px))] md:pt-8";

/**
 * 이 섹션으로 스크롤해 올 때 헤더 밑에 딱 붙게 하는 여백.
 * 목차(SectionNav) · 모바일 탭(DetailTabs) · 신청하기 버튼이 눌렸을 때 쓰인다.
 *
 * 모바일 112px = 헤더 64 + 탭 49 (실측)
 * 데스크톱 72px = 헤더 72 (탭 없음)
 *
 * ⚠️ 헤더(Header.tsx) 크기를 바꾸면 여기 숫자도 같이 고친다. CSS 변수를 못 쓴다 —
 *    scroll-margin 은 Tailwind 가 빌드 때 값으로 박는다.
 */
export const SCREEN_SCROLL_MARGIN = "scroll-mt-[7rem] md:scroll-mt-[4.5rem]";
