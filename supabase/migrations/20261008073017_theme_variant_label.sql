-- 모드 탭에 보여줄 짧은 이름 (바-ㅇ탈출 → 파티모드 / 노말모드)
--
-- 적용: test 20261008073017 (적용 완료, 2026-10-08) / 운영 (미적용)
--
-- 왜
--   테마명은 문자·어드민·정산에 그대로 나가야 해서 「바-ㅇ탈출 (노말모드)」처럼
--   길게 둔다. 화면의 모드 탭에는 짧은 이름이 필요한데, 테마명에서 괄호 안을
--   정규식으로 꺼내 쓰려다 보니 **괄호가 없는 파티모드가 '기본'으로 나왔다.**
--   이름 생김새에 기대지 말고 칸으로 적는다.
--
-- ⚠️ null 이면 화면이 모드 탭을 그릴 수 없다. 묶음(variant_group)에 속한 테마는
--    반드시 값을 넣는다. 단독 테마는 null 이어도 된다(탭 자체가 안 나온다).

alter table themes
  add column if not exists variant_label text;

comment on column themes.variant_label is
  '모드 탭에 보여줄 짧은 이름(파티모드/노말모드). 테마명과 별개다.';
