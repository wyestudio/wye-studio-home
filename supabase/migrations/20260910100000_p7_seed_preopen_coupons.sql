-- ── 원본 명세와 다르게 간 부분 (사장님 확정) ──────────────────
--
-- 1. 적용 단위: 문서는 "쿠폰 1장 = 1명분, 인원수만큼 사용 가능" 이었으나
--    **신청 건당 1장**으로 확정. 그래서 문서의 application_coupons 테이블과
--    복합 FK(종류 혼용 차단)는 만들지 않는다 — 여러 장을 붙일 때만 필요한 구조다.
--    매출 차감 상한도 40만원 → 20만원이 된다.
--
-- 2. 본인 쿠폰 양도: 문서대로 **허용**. restrict_to_issued_phone = false.
--
-- 3. pricing_tiers 테이블은 만들지 않는다. 같은 값이 theme_price_tiers 에 이미 있다
--    (1인 68,000 / 2인 62,000 / 3인 56,000 / 4인 50,000). 두 곳에 두면 가격이 갈린다.
--
-- 4. status='held' / held_until 흐름은 넣지 않는다. 30분 미입금 자동취소(Phase 5)가
--    아직 없어서, 지금 도입하면 쿠폰이 held 에 걸린 채 영영 안 풀린다.
--
-- ── 발급 대상 ────────────────────────────────────────────────
